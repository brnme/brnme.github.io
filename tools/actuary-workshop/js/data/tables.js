/* =====================================================================
 * 精算工坊 · js/data/tables.js
 * 基础发生率表 / 职业系数 / 医疗费率基准 / 校准因子（GDD §6.1）
 * 所有表为教学用简化表：按真实监管值/行业表量级校准（详见 README §口径声明）。
 * 环境兼容：浏览器(file://) 与 Node（校准脚本 eval 加载）。
 * ===================================================================== */
(function () {
  'use strict';
  var AW = (typeof window !== 'undefined') ? (window.AW = window.AW || {})
                                           : (globalThis.AW = globalThis.AW || {});

  /* ---------- 死亡率 qx（男，‰/年；"超优选生命表"口径，已含优选体+lapse校准） ----------
   * 女 = 男 × 0.5；年金定价再 × 0.75（养老金人群更长寿）。
   * 校准锚点：30岁男定寿市场价格（华贵大麦系 1132-1500 元/100万/30年）。 */
  var QX_M = [[20, 0.45], [25, 0.55], [30, 0.65], [35, 0.80], [40, 1.10], [45, 1.60],
              [50, 2.50], [55, 4.00], [60, 6.50], [65, 9.50], [70, 15.0], [75, 25.0],
              [80, 42.0], [85, 68.0], [90, 110], [95, 170], [100, 260], [104, 1000]];

  /* ---------- 重疾发生率（28病种合计，‰/年，男；女 ≈ 男×0.85） ----------
   * 锚点：2020版重疾表 30岁男 0.81‰；50岁后指数上升；中青年女<男。 */
  var CI_M = [[20, 0.45], [25, 0.60], [30, 0.81], [35, 1.15], [40, 1.80], [45, 3.00],
              [50, 5.00], [55, 8.00], [60, 12.0], [65, 18.0], [70, 26.0], [75, 36.0],
              [80, 48.0], [85, 60.0], [90, 72.0], [95, 85.0], [104, 100]];

  /* ---------- 长期护理失能发生率（重度失能，‰/年，男女同） ----------
   * 失能状态年死亡率 = 基础 qx × 3.5。 */
  var LTC_I = [[20, 0.2], [30, 0.3], [40, 0.6], [45, 1.0], [50, 1.8], [55, 3.5],
               [60, 6.0], [65, 10.0], [70, 16.0], [75, 25.0], [80, 38.0],
               [85, 55.0], [90, 75.0], [95, 95.0], [104, 120]];

  /* ---------- 医疗纯保费基准（元/年；有社保 / 1万免赔 / 经社保后100% / 含目录外）----------
   * 锚点：好医保长期医疗费率表（20岁149 / 30岁259 / 40岁467 / 60岁3139，中置信）。 */
  var MED_BASE = [[20, 150], [25, 200], [30, 260], [35, 320], [40, 470], [45, 620],
                  [50, 900], [55, 1500], [60, 3100], [65, 4300]];

  /* ---------- 意外（职业1类，男女同，18-65 基本平坦，‰/年） ---------- */
  var ACCIDENT = {
    deathRate: 0.30,        // 意外身故 0.30‰/年
    disabRate: 0.80,        // 伤残（任意等级）0.80‰/年
    disabAvgPay: 0.35,      // 加权平均给付比例 35%（1级100% → 10级10%）
    hospRate: 0.008,        // 意外住院发生率（津贴责任用），约0.8%/年
    medBase: 80,            // 意外医疗预期赔付 ≈80元/年（1类基准，0免赔100%）
    occ: { '1': 1.00, '2': 1.25, '3': 1.50, '4': 2.25, '5': 3.50, '6': 5.00 }
  };

  /* ---------- 医疗费率因子 ---------- */
  var MED_FACTORS = {
    deduct:   { '0': 3.0, '5000': 1.4, '10000': 1.0, '15000': 0.85, '20000': 0.72 },
    dirOut:   { 'yes': 1.0, 'no': 0.62 },      // 目录外责任
    special:  { 'yes': 1.0, 'no': 0.93 },      // 院外特药责任
    payRatio: { '100': 1.0, '80': 0.82, '60': 0.63 },
    renew:    { 'none': 1.0, 'y6': 1.08, 'y20': 1.18 }, // 保证续保的期权费
    sa:       { '100': 0.95, '200': 1.0, '300': 1.03, '400': 1.05, '600': 1.08 },
    noSocial: 2.2                              // 无社保客群（仅展示参考价）
  };

  /* =====================================================================
   * 校准因子（构建期以 GDD §6.5 基准区间标定；详见 README 附录）
   * 教学引擎为年度离散简化模型，下列因子吸收「市场经验 vs 教学表」的系统性偏差，
   * 使各险种基准配置的引擎输出落在 GDD §6.5 目标区间内。
   * ===================================================================== */
  var CALIB = {
    // —— 长期险给付端退保衰减（inforce_ben = kpx × (1-λ)^k）——
    wholeBenLapse: 0.0121,   // 终身寿：给付端轻衰减（长期失效/减额缴清教学口径，校准 2.4-2.9 万带）
    endowPremLapse: 0.005,  // 两全：保费端退保固定 1%（储蓄型继续率极高）
    endowBenLapse: 0.000,   // 两全给付端不衰减（满期金按保额等价口径，见 pricing 注）
    annuityPremLapse: 0.04, // 年金：保费端退保 4%（GDD：年金 lapse ≤4%）
    annuityFactor: 0.45,    // 年金给付定价经验因子（校准 ¥52k-58k 基准带）
    ciBenLapse: 0.049,     // 重疾给付端退保衰减（校准 ¥5.0-6.5k / 至70岁两带）
    ltcPremLapse: 0.05,     // 长护保费端退保固定 5%
    ltcBenLapse: 0.015,     // 长护给付端衰减（服务型给付，失效影响小）
    disabledQxMult: 3.5,    // 失能状态年死亡率 = 基础 qx × 3.5
    annuityQxMult: 0.75,    // 年金死亡率 = 基础 qx × 0.75
    femaleQx: 0.5,          // 女 = 男 × 0.5
    femaleCi: 0.85,         // 重疾发生率 女/男
    blendQx: 0.75,          // 性别=不限 时 qx 混合系数（(1+0.5)/2）
    blendCi: 0.925,         // 性别=不限 时 ci 混合系数（(1+0.85)/2）
    // —— 短期险 ——
    accidentFactor: 0.25,   // 意外经验因子（表值为人口口径，商业经核保后经验更低）
    medicalFactor: 0.78,    // 医疗基准校准因子
    accExpenseDefault: 15,  // 短期险附加费用率默认档（%）：意外
    medExpenseDefault: 12,  // 短期险附加费用率默认档（%）：医疗
    medInflationLoad: 0.03, // 通胀假设低于8%时，20年保证的医疗险审慎加载系数/百分点
    medInflationCoeff: { 'none': 0.5, 'y6': 1.2, 'y20': 2.2 } // 保证年限系数
  };

  /* ---------- 工具：5 岁带宽线性内插到整数年龄（超出表尾取端值） ---------- */
  function interp(table, age) {
    var a = Math.max(table[0][0], Math.min(table[table.length - 1][0], age));
    for (var k = 0; k < table.length - 1; k++) {
      var a0 = table[k][0], v0 = table[k][1], a1 = table[k + 1][0], v1 = table[k + 1][1];
      if (a >= a0 && a <= a1) return v0 + (v1 - v0) * (a - a0) / (a1 - a0);
    }
    return table[table.length - 1][1];
  }

  /* gender: 'M' 男 / 'F' 女 / 'X' 不限（混合费率） */
  function qx(age, gender, annuityBasis) {
    var f = gender === 'F' ? CALIB.femaleQx : (gender === 'X' ? CALIB.blendQx : 1);
    var q = interp(QX_M, age) / 1000 * f;
    if (annuityBasis) q *= CALIB.annuityQxMult;   // 年金人群更长寿
    return q;
  }
  function ciRate(age, gender) {
    var f = gender === 'F' ? CALIB.femaleCi : (gender === 'X' ? CALIB.blendCi : 1);
    return interp(CI_M, age) / 1000 * f;
  }
  function ltcRate(age) { return interp(LTC_I, age) / 1000; }
  function medBase(age) { return interp(MED_BASE, age); }

  AW.tables = {
    QX_M: QX_M, CI_M: CI_M, LTC_I: LTC_I, MED_BASE: MED_BASE,
    ACCIDENT: ACCIDENT, MED_FACTORS: MED_FACTORS, CALIB: CALIB,
    interp: interp, qx: qx, ciRate: ciRate, ltcRate: ltcRate, medBase: medBase,
    MAX_AGE: 105   // 表尾 104 岁处 qx=1000‰，即 105 岁前必然死亡
  };
})();
